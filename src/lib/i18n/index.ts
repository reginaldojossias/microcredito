export type Dictionary = typeof pt;

export const dictionaries: Record<Locale, Dictionary> = { pt, en };

export function getDictionary(locale: Locale): Dictionary {
  return dictionaries[locale];
}

export function createTranslator(locale: Locale) {
  const dict = getDictionary(locale);
  return function t<K extends keyof Dictionary>(
    section: K,
    key?: Dictionary[K] extends Record<string, unknown>
      ? keyof Dictionary[K]
      : never,
  ): string {
    const sectionValue = dict[section];
    if (key === undefined) return String(sectionValue);
    const value = (sectionValue as Record<string, unknown>)[key as string];
    return typeof value === "string" ? value : String(value);
  };
}

export function translateStatus(locale: Locale, status: string): string {
  const dict = getDictionary(locale);
  return (dict.status as Record<string, string>)[status] ?? status;
}
